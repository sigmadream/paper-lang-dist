def build_docx():
    src_path = BASE_DIR / 'KSII_TIIS_Word_Template.docx'
    dst_path = BASE_DIR / 'v1.5_KSII_TIIS.docx'

    shutil.copyfile(src_path, dst_path)
    doc = docx.Document(str(dst_path))

    # Update paragraphs while preserving embedded graphics and KSII TIIS styles
    for idx, p in enumerate(doc.paragraphs):
        if idx in p_trans:
            p.text = p_trans[idx]

    # Update tables
    for t_idx, t_data in tables_trans.items():
        if t_idx < len(doc.tables):
            table = doc.tables[t_idx]
            if len(table.rows) > 0:
                header_row = table.rows[0]
                for c_idx, cell in enumerate(header_row.cells):
                    if c_idx < len(t_data['headers']):
                        cell.text = t_data['headers'][c_idx]
            for r_idx, row_vals in enumerate(t_data['rows']):
                if r_idx + 1 < len(table.rows):
                    row = table.rows[r_idx + 1]
                    for c_idx, cell in enumerate(row.cells):
                        if c_idx < len(row_vals):
                            cell.text = row_vals[c_idx]

    doc.save(str(dst_path))
    print(f"Saved {dst_path.name} successfully.")


